import os, glob, re, requests, kagglehub
import matplotlib.pyplot as plt
import torch
from torch import nn, optim
from PIL import Image
from scipy.io import loadmat
from torch.utils.data import Dataset, DataLoader
from torchvision.models import mobilenet_v3_small, MobileNet_V3_Small_Weights
from sklearn.metrics import accuracy_score, precision_score, recall_score, confusion_matrix

path = kagglehub.dataset_download("arjun2000ashok/vggflowers")

meta = "/content/flowers_metadata"
os.makedirs(meta, exist_ok=True)

for name in ["imagelabels.mat", "setid.mat"]:
    url = f"https://thor.robots.ox.ac.uk/flowers/102/{name}"
    r = requests.get(url)
    r.raise_for_status()

    with open(os.path.join(meta, name), "wb") as f:
        f.write(r.content)

labels = loadmat(meta + "/imagelabels.mat")["labels"].ravel() - 1
splits = loadmat(meta + "/setid.mat")

images = glob.glob(path + "/**/*.jpg", recursive=True)
images.sort(key=lambda p: int(re.search(r"\d+", os.path.basename(p)).group()))

train_ids = splits["trnid"].ravel() - 1
test_ids = splits["tstid"].ravel() - 1

weights = MobileNet_V3_Small_Weights.DEFAULT
transform = weights.transforms()

class Flowers(Dataset):
    def __init__(self, ids):
        self.ids = ids

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, index):
        i = self.ids[index]
        image = Image.open(images[i]).convert("RGB")
        return transform(image), int(labels[i])

train_loader = DataLoader(Flowers(train_ids), batch_size=32)
test_loader = DataLoader(Flowers(test_ids), batch_size=32)

model = mobilenet_v3_small(weights=weights)

for p in model.features.parameters():
    p.requires_grad = False

model.classifier = nn.Sequential(
    nn.Linear(model.classifier[0].in_features, 256),
    nn.Hardswish(),
    nn.Dropout(0.2),
    nn.Linear(256, 102)
)

criterion = nn.CrossEntropyLoss()

def train(epochs, optimizer, fine=False):
    for epoch in range(epochs):
        model.train()
        model.features.eval()

        if fine:
            model.features[-2:].train()

        for x, y in train_loader:
            optimizer.zero_grad()
            loss = criterion(model(x), y)
            loss.backward()
            optimizer.step()

def evaluate():
    model.eval()
    true, pred = [], []

    with torch.no_grad():
        for x, y in test_loader:
            predictions = model(x).argmax(1)
            true.extend(y.tolist())
            pred.extend(predictions.cpu().tolist())

    scores = [
        accuracy_score(true, pred),
        precision_score(true, pred, average="weighted", zero_division=0),
        recall_score(true, pred, average="weighted", zero_division=0)
    ]

    print(f"Accuracy: {scores[0] * 100:.2f}%")
    print(f"Precision: {scores[1] * 100:.2f}%")
    print(f"Recall: {scores[2] * 100:.2f}%")

    return true, pred, scores

optimizer = optim.Adam(model.classifier.parameters(), lr=0.001)
train(5, optimizer)
y_true, y_pred, fe = evaluate()

plt.imshow(confusion_matrix(y_true, y_pred, labels=range(102)))
plt.colorbar()
plt.show()

for p in model.features[-2:].parameters():
    p.requires_grad = True

optimizer = optim.Adam(filter(lambda p: p.requires_grad, model.parameters()), lr=0.0001)
train(3, optimizer, True)
_, _, ft = evaluate()