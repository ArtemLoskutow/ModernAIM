import numpy as np
from sklearn import preprocessing, model_selection
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.metrics import f1_score, precision_score, recall_score

# Входной файл,
input_file = 'income_data.txt'

# Чтение данных
X = []
y = []
count_class1 = 0
count_class2 = 0
max_datapoints = 5000

with open(input_file, 'r') as f:
  for line in f.readlines():
    if count_class1 >= max_datapoints and count_class2 >= max_datapoints:
      break
    if '?' in line:
      continue
    data = line[:-1].split(', ')
    if data[-1] == '<=50K' and count_class1 < max_datapoints:
      X.append(data)
      count_class1 += 1
    if data[-1] == '>50K' and count_class2 < max_datapoints:
      X.append(data)
      count_class2 += 1

# Преобразование в массив numpy array
X = np.array(X)

# Преобразование строковых данных в числовые
label_encoder = []
X_encoded = np.empty(X.shape)
for i,item in enumerate(X[0]):
  if item.isdigit():
    X_encoded[:, i] = X[:, i]
  else:
    label_encoder.append(preprocessing.LabelEncoder())
    X_encoded[:, i] = label_encoder[-1].fit_transform(X[:, i])
X = X_encoded[:, :-1].astype(int)
y = X_encoded[:, -1].astype(int)

# Перекрестная проверка
X_train, X_test, y_train, y_test = model_selection.train_test_split(X, y, test_size=0.2, random_state=5)

parameters = [('linear', 1),('linear', 10),('rbf', 1),('poly', 1)]

input_data_list = [['37', 'Private', '215646', 'HS-grad', '9', 'Never-married',
                        'Handlers-cleaners', 'Not-in-family', 'White', 'Male',
                        '0', '0', '40', 'United-States'],
                       ['52', 'Self-emp-not-inc', '209642', 'HS-grad', '9', 'Married-civ-spouse',
                        'Exec-managerial', 'Husband', 'White', 'Male',
                        '0', '0', '45', 'United-States'],
                       ['29', 'Private', '190000', 'Bachelors', '13', 'Never-married',
                        'Prof-specialty', 'Not-in-family', 'White', 'Female',
                        '0', '0', '40', 'United-States']]

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

for kernel, C in parameters:
    classifier = SVC(kernel=kernel, C=C, random_state=0)

    classifier.fit(X_train_scaled, y_train)
    y_test_pred = classifier.predict(X_test_scaled)

    f1 = f1_score(y_test, y_test_pred, average='weighted')
    precision = precision_score(y_test, y_test_pred, average='weighted')
    recall = recall_score(y_test, y_test_pred, average='weighted')

    print('\nKernel:', kernel, 'C:', C)
    print('F1 score:', round(f1 * 100, 2), '%')
    print('Precision:', round(precision * 100, 2), '%')
    print('Recall:', round(recall * 100, 2), '%')

    for number, input_data in enumerate(input_data_list, start=1):
        input_data_encoded = [-1] * len(input_data)
        count = 0

        for i, item in enumerate(input_data):
            if item.isdigit():
                input_data_encoded[i] = int(item)
            else:
                input_data_encoded[i] = label_encoder[count].transform([item])[0]
                count += 1

        input_data_encoded = np.array(input_data_encoded, dtype=float).reshape(1, -1)
        input_data_scaled = scaler.transform(input_data_encoded)

        predicted_class = classifier.predict(input_data_scaled)
        predicted_label = label_encoder[-1].inverse_transform(predicted_class)[0]

        print(f'Точка {number}: {predicted_label}')